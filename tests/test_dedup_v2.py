os.environ.setdefault("OPENAI_API_KEY", "test-key-for-mocks")

from tests.dedup_v2_support import (  # noqa: E402
    MUST_LINK,
    MUST_LINK_FOR_REVIEW,
    MUST_MERGE,
    MUST_NOT_MERGE,
    STRUCTURAL_MUST_NOT_MERGE,
    V2_FLAGS,
    XFAIL,
    AlwaysSameEntityLLM,
    SpecOracleLLM,
    V1ReplayLLM,
    cluster_of,
    describe,
    fixture_dedup_rows,
    load_fixture,
    run_clustering,
)

#: How much more the model may be consulted with the flags on than without.
#: Delivery-point blocking deliberately widens what is comparable (a house-less
#: row reaches its neighbours, two zips join on city+house), and slot
#: classification moves rows across the Name-2 boundary — both create calls
#: that v1 never made. The budget is here so that widening stays a considered
#: cost rather than an unnoticed one; the exact counts are in the report.
LLM_CALL_BUDGET_RATIO = 3.0


def _run(double_cls, flags_on: bool):
    """One clustering pass at a given flag setting. Module-scoped, so the
    parametrised assertions below all read one run rather than 60."""
    with pytest.MonkeyPatch.context() as monkeypatch:
        for flag in V2_FLAGS:
            monkeypatch.setenv(flag, "true" if flags_on else "false")
        fixture = load_fixture()
        rows = fixture_dedup_rows(fixture)
        llm = double_cls(fixture)
        results, summary = asyncio.run(run_clustering(rows, llm))
    return fixture, results, summary, llm


@pytest.fixture(scope="module")
def oracle_run():
    """Flags on, adjudicated by a model that is always right."""
    return _run(SpecOracleLLM, flags_on=True)


@pytest.fixture(scope="module")
def adversary_run():
    """Flags on, adjudicated by a model that is always wrong in one direction."""
    return _run(AlwaysSameEntityLLM, flags_on=True)


