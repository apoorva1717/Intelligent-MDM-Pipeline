"""The dedup v2 expectations, asserted with all three flags on.

The fixture is the 200-row stress batch (tests/fixtures/dedup_v2_stress_200.json,
regenerated by tools/build_dedup_v2_fixture.py). The expectation tables live in
tests/dedup_v2_support.py, transcribed from the change request.

Two doubles, two different claims — each test says which one it is making:

* ``SpecOracleLLM`` — a perfect adjudicator. A failure here is the machinery's:
  blocking, slot classification, bucketing or a guard either forbade a merge
  the tables require or forced one they forbid. This is the claim the flags
  exist to make true.
* ``AlwaysSameEntityLLM`` — an adjudicator that says "same entity" to
  everything. It answers the two questions no model-dependent test can:
  did these rows ever reach one block and get compared (MUST_MERGE), and is
  this separation structural rather than a matter of the model's opinion
  (STRUCTURAL_MUST_NOT_MERGE)?

Cluster ids are content hashes of their members, so every assertion is about
set membership, never a literal id.

Neither double says what the live deployment would answer. That is a separate,
reported measurement — see the change report — not something a test can claim.
"""

from __future__ import annotations

