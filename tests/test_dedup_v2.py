# MUST_LINK — same organisation, different site
# ---------------------------------------------------------------------------

def link_of(results, row_id):
    """A row's Link ID, or None while the column does not exist yet."""
    return getattr(results.get(row_id), "link_id", None)


@pytest.mark.parametrize("group", sorted(MUST_LINK), ids=sorted(MUST_LINK))
def test_must_link_shares_one_link_id(group, oracle_run) -> None:
    """One organisation across several delivery points is ONE Link ID.

    This is the column that carries a same-organisation finding without
    asserting a duplicate, so a missing link is a lost finding — the records
    are related and nothing in the output would say so.
    """
    _fixture, results, _summary, _llm = oracle_run
    spec = MUST_LINK[group]
    links = {row_id: link_of(results, row_id) for row_id in spec.rows}
    assert len(set(links.values())) == 1 and None not in links.values(), (
        f"{group}: expected one shared Link ID.\n{spec.why}\ngot {links}\n"
        f"{describe(results, spec.rows)}"
    )


@pytest.mark.parametrize("group", sorted(MUST_LINK), ids=sorted(MUST_LINK))
def test_must_link_never_clusters_across_sites(group, oracle_run) -> None:
    """A Link is not a Cluster: different sites keep different Cluster IDs."""
    _fixture, results, _summary, _llm = oracle_run
    spec = MUST_LINK[group]
    violations = []
    for i, site in enumerate(spec.sites):
        here = {cluster_of(results, row_id) for row_id in site} - {None}
        for other in spec.sites[i + 1:]:
            there = {cluster_of(results, row_id) for row_id in other} - {None}
            for shared in here & there:
                violations.append((site, other, shared))
    assert not violations, (
        f"{group}: sites share a Cluster ID {violations}\n{spec.why}\n"
        f"{describe(results, spec.rows)}"
    )


