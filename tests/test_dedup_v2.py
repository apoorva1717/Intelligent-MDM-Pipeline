def test_flags_on_does_not_explode_the_call_count() -> None:
    """What the widening costs in model calls, measured rather than assumed.

    Both runs use the same double, so the only difference is what the code
    decided to ask about.
    """
    _f_off, _r_off, off_summary, _l_off = _run(V1ReplayLLM, flags_on=False)
    _f_on, _r_on, on_summary, _l_on = _run(V1ReplayLLM, flags_on=True)
    assert off_summary.llm_calls > 0, "the flags-off run consulted no model at all"
    assert on_summary.llm_calls <= off_summary.llm_calls * LLM_CALL_BUDGET_RATIO, (
        f"flags-on made {on_summary.llm_calls} LLM calls against "
        f"{off_summary.llm_calls} with the flags off — over the "
        f"{LLM_CALL_BUDGET_RATIO}x budget"
    )
