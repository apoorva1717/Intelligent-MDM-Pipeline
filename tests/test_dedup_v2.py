_NOT_MERGE_IDS = [label for label, _anchors, _forbidden in MUST_NOT_MERGE]


@pytest.mark.parametrize(
    ("label", "anchors", "forbidden"), MUST_NOT_MERGE, ids=_NOT_MERGE_IDS
)
def test_must_not_merge(label, anchors, forbidden, oracle_run) -> None:
    _fixture, results, _summary, _llm = oracle_run
    anchor_clusters = {cluster_of(results, row_id) for row_id in anchors} - {None}
    violations = [
        (row_id, cluster_of(results, row_id))
        for row_id in forbidden
        if cluster_of(results, row_id) is not None
        and cluster_of(results, row_id) in anchor_clusters
    ]
    # Only anchor-against-forbidden. Whether two forbidden rows belong together
    # is a separate question that this table does not answer: the two
    # address-less NASA rows are a real judgement call about "Ames Research
    # Center" against "Intelligent Systems Division / Ames Research Center",
    # and it lives in MODEL_JUDGEMENT. HP against HPE needs no extra rule —
    # one is the anchor and the other is forbidden against it.
    assert not violations, (
        f"{label}: {violations} share a cluster with the anchor group {anchors}\n"
        f"{describe(results, [*anchors, *forbidden])}"
    )


_STRUCTURAL = [
    (label, anchors, forbidden)
    for label, anchors, forbidden in MUST_NOT_MERGE
    if label in STRUCTURAL_MUST_NOT_MERGE
]


@pytest.mark.parametrize(
    ("label", "anchors", "forbidden"), _STRUCTURAL, ids=[t[0] for t in _STRUCTURAL]
)
def test_structural_must_not_merge_survives_a_wrong_model(
    label, anchors, forbidden, adversary_run
) -> None:
    """A different house number is not a judgement call.

    These separations come from the delivery point, so no model verdict is ever
    consulted across them and an adjudicator that merges everything cannot
    join them. If one of these fails, blocking let two delivery points into one
    block — the failure mode B exists to close.
    """
    _fixture, results, _summary, _llm = adversary_run
    anchor_clusters = {cluster_of(results, row_id) for row_id in anchors} - {None}
    violations = [
        (row_id, cluster_of(results, row_id))
        for row_id in forbidden
        if cluster_of(results, row_id) is not None
        and cluster_of(results, row_id) in anchor_clusters
    ]
    assert not violations, (
        f"{label}: blocking let {violations} into the anchor cluster {anchors}\n"
        f"{describe(results, [*anchors, *forbidden])}"
    )


