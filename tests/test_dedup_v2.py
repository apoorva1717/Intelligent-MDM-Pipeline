@pytest.mark.parametrize("group", sorted(MUST_MERGE), ids=sorted(MUST_MERGE))
def test_must_merge_shares_one_cluster(group, oracle_run) -> None:
    _fixture, results, _summary, _llm = oracle_run
    row_ids = MUST_MERGE[group]
    clusters = {cluster_of(results, row_id) for row_id in row_ids}
    assert len(clusters) == 1 and None not in clusters, (
        f"{group}: expected one shared Cluster ID across {row_ids}, got "
        f"{sorted(str(c) for c in clusters)}\n{describe(results, row_ids)}"
    )


@pytest.mark.parametrize("group", sorted(MUST_MERGE), ids=sorted(MUST_MERGE))
def test_must_merge_rows_are_comparable_at_all(group, adversary_run) -> None:
    """Blocking and nomination reach these rows, whatever the model thinks.

    Under an adjudicator that merges everything it is asked about, a group that
    still fails to cluster was never asked: its rows landed in different blocks
    or no rule nominated the pair. That is a blocking result and nothing else,
    which is why it is asserted separately from the oracle run above.
    """
    _fixture, results, _summary, _llm = adversary_run
    row_ids = MUST_MERGE[group]
    clusters = {cluster_of(results, row_id) for row_id in row_ids}
    assert len(clusters) == 1 and None not in clusters, (
        f"{group}: rows never became comparable — {sorted(str(c) for c in clusters)}\n"
        f"{describe(results, row_ids)}"
    )


